#!/usr/bin/env python3
"""Generates web/i18n.js and the Android it.ampy.cybercity.L class from tools/i18n_dict.py."""
import json, pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / 'tools'))
from i18n_dict import PAIRS
seen = {}
for a, b in PAIRS: seen.setdefault(a, b)
pairs = sorted(seen.items(), key=lambda p: -len(p[0]))
js = """/* Cybercity 3D i18n — generated by tools/gen_i18n.py. English by default; IT/EN switch kept in localStorage.
   Translates every canvas text (HUDs) and every DOM text / placeholder, so the pages need no other change. */
(function () {
  'use strict';
  const PAIRS = %s;
  const map = new Map(PAIRS), LET = 'A-Za-z\\u00C0-\\u00FF';
  const esc = s => s.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&'), isL = c => /[A-Za-z\\u00C0-\\u00FF]/.test(c);
  const re = new RegExp(PAIRS.map(([k]) => (isL(k[0]) ? '(?<![' + LET + '])' : '') + esc(k) + (isL(k[k.length - 1]) ? '(?![' + LET + '])' : '')).join('|'), 'g');
  const q = new URLSearchParams(location.search);
  if (q.has('lang')) try { localStorage.setItem('lang', q.get('lang')); } catch (e) { }
  let lang = 'en'; try { lang = localStorage.getItem('lang') || 'en'; } catch (e) { }
  const cache = new Map();
  function tr(s) {
    if (lang === 'it' || typeof s !== 'string' || !s) return s;
    let r = cache.get(s); if (r !== undefined) return r;
    r = s.replace(re, m => map.get(m) || m);
    if (cache.size > 5000) cache.clear(); cache.set(s, r); return r;
  }
  window.tr = tr; window.LANG = lang;
  window.setLang = l => { try { localStorage.setItem('lang', l); } catch (e) { } location.reload(); };
  const C2 = CanvasRenderingContext2D.prototype;
  for (const fn of ['fillText', 'strokeText', 'measureText']) { const o = C2[fn]; C2[fn] = function (t, ...a) { return o.call(this, tr(String(t)), ...a); }; }
  if (lang === 'it') return;
  // DOM: translate text nodes, placeholders and titles as they appear or change
  const doNode = n => {
    if (n.nodeType === 3) { const pe = n.parentNode; if (pe && (pe.nodeName === 'SCRIPT' || pe.nodeName === 'STYLE')) return; const t = n.nodeValue, r = tr(t); if (r !== t) n.nodeValue = r; return; }
    if (n.nodeType !== 1 || n.tagName === 'SCRIPT' || n.tagName === 'STYLE') return;
    if (n.placeholder) { const r = tr(n.placeholder); if (r !== n.placeholder) n.placeholder = r; }
    if (n.title) { const r = tr(n.title); if (r !== n.title) n.title = r; }
    for (const c of n.childNodes) doNode(c);
  };
  const obs = new MutationObserver(ms => { for (const m of ms) { if (m.type === 'characterData') doNode(m.target); else for (const a of m.addedNodes) doNode(a); } });
  const start = () => { doNode(document.body || document.documentElement); document.title = tr(document.title); obs.observe(document.documentElement, { childList: true, subtree: true, characterData: true }); };
  if (document.body) start(); else document.addEventListener('DOMContentLoaded', start);
  // small language switch (bottom-left corner)
  addEventListener('load', () => {
    if (/[?&](demo|auto)=/.test(location.search) || window.top !== window) return;   // screensaver scenes: no UI
    const b = document.createElement('div'); b.id = 'langPill';
    b.textContent = 'EN · IT'; b.title = 'Language / Lingua';
    b.style.cssText = 'position:fixed;left:6px;bottom:6px;z-index:9999;font:bold 11px monospace;color:#ecfcff;background:rgba(7,11,19,.55);border:1px solid rgba(0,255,227,.5);border-radius:9px;padding:3px 7px;opacity:.75;cursor:pointer';
    b.onclick = () => window.setLang(lang === 'it' ? 'en' : 'it');
    document.body.appendChild(b);
  });
})();
""" % json.dumps(pairs, ensure_ascii=False)
(root / 'web/i18n.js').write_text(js)
def jstr(s): return json.dumps(s, ensure_ascii=False)
java_pairs = ',\n        '.join('{' + jstr(a) + ', ' + jstr(b) + '}' for a, b in pairs)
java = """package it.ampy.cybercity;

import android.content.Context;

import java.util.HashMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/** Interface language (generated by tools/gen_i18n.py): English by default, Italian on request.
 *  L.t() translates any UI text by replacing the known Italian phrases, longest first, on word boundaries. */
public final class L {
    private L() { }
    private static volatile boolean en = true, ready = false;
    private static Pattern P; private static final HashMap<String, String> M = new HashMap<>(), C = new HashMap<>();
    private static final String[][] PAIRS = {
        %s
    };
    public static void init(Context c) {
        en = !"it".equals(c.getSharedPreferences(c.getPackageName() + "_preferences", Context.MODE_PRIVATE).getString("lang", "en"));
    }
    public static boolean english() { return en; }
    public static void set(Context c, boolean english) {
        c.getSharedPreferences(c.getPackageName() + "_preferences", Context.MODE_PRIVATE).edit().putString("lang", english ? "en" : "it").commit();
        en = english; synchronized (C) { C.clear(); }
    }
    private static synchronized void build() {
        if (ready) return;
        StringBuilder sb = new StringBuilder();
        for (String[] p : PAIRS) {
            M.put(p[0], p[1]);
            if (sb.length() > 0) sb.append('|');
            String k = p[0];
            if (Character.isLetter(k.charAt(0))) sb.append("(?<![\\\\p{L}])");
            sb.append(Pattern.quote(k));
            if (Character.isLetter(k.charAt(k.length() - 1))) sb.append("(?![\\\\p{L}])");
        }
        P = Pattern.compile(sb.toString());
        ready = true;
    }
    public static String t(String s) {
        if (!en || s == null || s.isEmpty()) return s;
        synchronized (C) { String r = C.get(s); if (r != null) return r; }
        build();
        Matcher m = P.matcher(s); StringBuffer out = new StringBuffer();
        while (m.find()) { String v = M.get(m.group()); m.appendReplacement(out, Matcher.quoteReplacement(v != null ? v : m.group())); }
        m.appendTail(out);
        String r = out.toString();
        synchronized (C) { if (C.size() > 4000) C.clear(); C.put(s, r); }
        return r;
    }
    public static String[] all(String[] a) { String[] o = new String[a.length]; for (int i = 0; i < a.length; i++) o[i] = t(a[i]); return o; }
}
""" % java_pairs
(root / 'app/src/main/java/it/ampy/cybercity/L.java').write_text(java)
print('i18n:', len(pairs), 'phrases')
